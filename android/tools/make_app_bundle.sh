#!/bin/bash
#  Wrap the built engine in a minimal .app bundle.
#
#  Two reasons this is worth having:
#    * double-clickable, with a Dock icon and a real name, like any Mac app;
#    * a bare executable is not an "application" to macOS -- it has no bundle
#      identifier, so it never appears in the installed-apps index and cannot
#      be addressed by name by the accessibility/automation APIs.
#
#  usage: make_app_bundle.sh <silentstorm_mac binary> <retail data dir> [out dir]
set -euo pipefail

BIN=${1:?usage: make_app_bundle.sh <binary> <data dir> [out dir]}
DATA=${2:?usage: make_app_bundle.sh <binary> <data dir> [out dir]}
OUT=${3:-$(dirname "$BIN")}

[ -x "$BIN" ]  || { echo "not executable: $BIN" >&2; exit 1; }
[ -d "$DATA" ] || { echo "no such data directory: $DATA" >&2; exit 1; }

BIN=$(cd "$(dirname "$BIN")" && pwd)/$(basename "$BIN")
DATA=$(cd "$DATA" && pwd)
APP="$OUT/SilentStorm.app"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleName</key><string>SilentStorm</string>
	<key>CFBundleDisplayName</key><string>Silent Storm</string>
	<key>CFBundleIdentifier</key><string>org.ss.macport.silentstorm</string>
	<key>CFBundleExecutable</key><string>SilentStorm</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleShortVersionString</key><string>1.0</string>
	<key>CFBundleVersion</key><string>1</string>
	<key>NSHighResolutionCapable</key><true/>
	<key>LSMinimumSystemVersion</key><string>11.0</string>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/SilentStorm" <<LAUNCHER
#!/bin/bash
# generated by tools/make_app_bundle.sh -- the engine takes the retail data
# directory as argv[1], and stdout/stderr carry the whole boot report.
exec "$BIN" "$DATA" > /tmp/ss-port.log 2>&1
LAUNCHER
chmod +x "$APP/Contents/MacOS/SilentStorm"

echo "built $APP"
echo "  engine: $BIN"
echo "  data:   $DATA"
echo "  log:    /tmp/ss-port.log"
